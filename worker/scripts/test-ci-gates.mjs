// The CI gates, and the promises their YAML makes.
//
// A workflow is code that runs on someone else's machine, on a schedule
// nobody watches, against a repository we cannot see. The failure modes are
// specific and all of them are quiet:
//
//   * A gate that goes red the day it is switched on gets deleted. Every
//     setup problem — no secret, no config file, an API that is down — has to
//     be a NOTICE, not a failure.
//   * A gate that fails a build must say WHY in words a reviewer can act on,
//     in the pull request, not only in a log nobody opens.
//   * A gate that silently stops running is worse than one that never ran.
//
// And one specific to this product: the estimator gate must not acquire the
// ability to touch a cloud account. It exists to price a committed file, and
// the moment it accepts a credential it becomes a different product with a
// different threat model.
//
// The YAML shipped to customers and the YAML committed in this repo are
// generated by the same functions, so this suite checks the generator and the
// committed copies together — a drift between what we tell people to run and
// what we run ourselves is how the advice goes stale.
//
// Run with:  node scripts/test-ci-gates.mjs

import { readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import {
  buildWorkflow, buildOptimizerWorkflow, buildEstimateWorkflow,
  buildArchitectureWorkflow, buildBudgetExample, buildOptimizerConfigExample,
} from "../src/handlers/ci.js";
import {
  ciSnippetHandler, ciOptimizerSnippetHandler,
  ciEstimateSnippetHandler, ciArchitectureSnippetHandler,
} from "../src/handlers/ci.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, "..", "..");
const ORIGIN = "https://algosize.com";

let failures = 0;
const ok   = (m) => console.log(`  \x1b[32m✓\x1b[0m ${m}`);
const fail = (m) => { console.log(`  \x1b[31m✗\x1b[0m ${m}`); failures++; };
const expect = (c, l) => (c ? ok(l) : fail(l));
const group  = (n) => console.log(`\n\x1b[1m${n}\x1b[0m\n`);

const GATES = [
  { name: "dependency audit", yaml: buildWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algosize-audit.yml" },
  { name: "algorithm optimizer", yaml: buildOptimizerWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algorithm-optimizer.yml" },
  { name: "infrastructure cost", yaml: buildEstimateWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algosize-estimate.yml" },
  { name: "architecture", yaml: buildArchitectureWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algosize-architecture.yml" },
];

// ===========================================================================
group("every gate is safe to switch on");
// ===========================================================================
for (const g of GATES) {
  // The one universal rule: a missing secret is a notice and an exit 0.
  expect(/ALGOSIZE_API_KEY/.test(g.yaml),
    `${g.name} — reads the shared ALGOSIZE_API_KEY secret`);
  expect(/::notice::/.test(g.yaml),
    `${g.name} — has a notice path, so setup problems are not failures`);
  expect(!/\$\{\{\s*secrets\.\w+\s*\}\}/.test(g.yaml.replace(/ALGOSIZE_API_KEY/g, "")) ||
         (g.yaml.match(/secrets\./g) || []).every((_, i, a) => a.length <= 6),
    `${g.name} — needs no secret beyond that one`);
  expect(/permissions:/.test(g.yaml),
    `${g.name} — declares its permissions rather than inheriting the default token`);
  expect(!/permissions:[\s\S]{0,120}contents:\s*write/.test(g.yaml),
    `${g.name} — never asks for write access to the repository`);
}

// ===========================================================================
group("the estimator gate cannot reach a cloud account");
// ===========================================================================
{
  const yaml = buildEstimateWorkflow({ origin: ORIGIN });
  // The product promise is "no cloud-account connector, no credential
  // storage". A CI gate is the most natural place for that to erode, because
  // adding a role ARN would make the numbers better and the reviewer of that
  // pull request would probably say yes.
  const CLOUD_SECRETS = [
    "AWS_ACCESS_KEY", "AWS_SECRET", "AWS_SESSION_TOKEN", "AWS_ROLE",
    "role-to-assume", "aws-actions/configure-aws-credentials",
    "azure/login", "AZURE_CREDENTIALS", "google-github-actions/auth",
    "GOOGLE_APPLICATION_CREDENTIALS", "KUBECONFIG", "HCLOUD_TOKEN",
    "DIGITALOCEAN", "id-token: write",
  ];
  for (const s of CLOUD_SECRETS) {
    expect(!yaml.includes(s), `no ${s} anywhere in the estimator gate`);
  }
  expect(/not your bill/i.test(yaml),
    "and every comment it posts repeats that these are list prices, not an invoice");
  expect(/no cloud account was contacted/i.test(yaml),
    "…and says outright that nothing was contacted");
}

// ===========================================================================
group("a gate that fails says why, in the pull request");
// ===========================================================================
for (const g of GATES) {
  const fails = /exit 1/.test(g.yaml);
  if (!fails) { ok(`${g.name} — never fails a build by design`); continue; }
  expect(/::error::/.test(g.yaml),
    `${g.name} — an exit 1 is preceded by an ::error:: annotation`);
  expect(/gh pr comment|sticky|comment\.md|createComment/.test(g.yaml),
    `${g.name} — and the reasoning lands in the pull request, not only in the log`);
}

// ===========================================================================
group("thresholds default to annotate, not to fail");
// ===========================================================================
{
  // Switching a gate on must never be the thing that turns a repository red.
  // Whoever enables it should get a week of annotations first and raise the
  // threshold deliberately.
  expect(/monthlyCeilingUsd": null/.test(buildBudgetExample()),
    "the budget example ships with no ceiling — annotate first, gate later");
  expect(/arch_fail_on:"none"|arch_fail_on: *"none"/.test(buildArchitectureWorkflow({ origin: ORIGIN })),
    "the architecture gate defaults to arch_fail_on none");
  expect(/one bucket above/.test(buildOptimizerConfigExample()),
    "the optimizer example tells you to set a ceiling above the true complexity, " +
    "so timing noise cannot fail a build");
}

// ===========================================================================
group("the snippet endpoints serve the same YAML we commit");
// ===========================================================================
{
  const env = { SITE_ORIGIN: ORIGIN };
  const cases = [
    ["audit",        ciSnippetHandler,             buildWorkflow({ origin: ORIGIN })],
    ["optimizer",    ciOptimizerSnippetHandler,    buildOptimizerWorkflow({ origin: ORIGIN })],
    ["estimate",     ciEstimateSnippetHandler,     buildEstimateWorkflow({ origin: ORIGIN })],
    ["architecture", ciArchitectureSnippetHandler, buildArchitectureWorkflow({ origin: ORIGIN })],
  ];
  for (const [name, handler, expected] of cases) {
    const body = await handler(new Request("https://x/api/ci/" + name), env).json();
    expect(body.workflow === expected,
      `/api/ci/${name}-snippet serves the generated workflow verbatim`);
    expect(typeof body.filename === "string" && body.filename.startsWith(".github/workflows/"),
      `…and names where it goes`);
    // The snippet cannot contain a key: this endpoint has no access to key
    // plaintext (only sha256 hashes are stored), which makes that structural.
    expect(!/ask_live_/.test(body.workflow),
      `…and never embeds a key, only the secret's name`);
  }
}

// ===========================================================================
group("what we tell customers to run is what we run ourselves");
// ===========================================================================
for (const g of GATES) {
  const path = join(REPO, g.file);
  if (!existsSync(path)) {
    fail(`${g.name} — ${g.file} is committed in this repository`);
    continue;
  }
  ok(`${g.name} — ${g.file} is committed in this repository`);
  const onDisk = readFileSync(path, "utf8");
  // The audit workflow predates the generator and carries local edits; the
  // two generated ones must match byte for byte, or the advice we serve has
  // drifted from the thing we have actually watched run.
  if (g.file.includes("estimate") || g.file.includes("architecture")) {
    expect(onDisk === g.yaml,
      `…and is byte-identical to what /api/ci/*-snippet serves`);
  }
}

console.log("");
if (failures) {
  console.log(`\x1b[31m  ${failures} ci-gate test(s) failed\x1b[0m`);
  process.exit(1);
}
console.log("\x1b[32m  all ci-gate tests passed\x1b[0m");
