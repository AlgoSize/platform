// The CI gates, and the promises their YAML makes.
//
// A workflow is code that runs on someone else's machine, on a schedule
// nobody watches, against a repository we cannot see. The failure modes are
// specific and all of them are quiet:
//
//   * A gate that goes red the day it is switched on gets deleted. Every
//     setup problem — no secret, no config file, an API that is down — has to
//     be a NOTICE, not a failure.
//   * A gate that fails a build must say WHY in words a reviewer can act on,
//     in the pull request, not only in a log nobody opens.
//   * A gate that silently stops running is worse than one that never ran.
//
// And one specific to this product: the estimator gate must not acquire the
// ability to touch a cloud account. It exists to price a committed file, and
// the moment it accepts a credential it becomes a different product with a
// different threat model.
//
// The YAML shipped to customers and the YAML committed in this repo are
// generated by the same functions, so this suite checks the generator and the
// committed copies together — a drift between what we tell people to run and
// what we run ourselves is how the advice goes stale.
//
// Run with:  node scripts/test-ci-gates.mjs

import { readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import {
  buildWorkflow, buildOptimizerWorkflow, buildEstimateWorkflow,
  buildArchitectureWorkflow, buildBudgetExample, buildOptimizerConfigExample, buildCostWorkflow } from "../src/handlers/ci.js";
import {
  ciSnippetHandler, ciOptimizerSnippetHandler,
  ciEstimateSnippetHandler, ciArchitectureSnippetHandler,
} from "../src/handlers/ci.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, "..", "..");
const ORIGIN = "https://algosize.com";

let failures = 0;
const ok   = (m) => console.log(`  \x1b[32m✓\x1b[0m ${m}`);
const fail = (m) => { console.log(`  \x1b[31m✗\x1b[0m ${m}`); failures++; };
const expect = (c, l) => (c ? ok(l) : fail(l));
const group  = (n) => console.log(`\n\x1b[1m${n}\x1b[0m\n`);

const GATES = [
  { name: "dependency audit", yaml: buildWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algosize-audit.yml" },
  { name: "algorithm optimizer", yaml: buildOptimizerWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algorithm-optimizer.yml" },
  { name: "infrastructure cost", yaml: buildEstimateWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algosize-estimate.yml" },
  { name: "architecture", yaml: buildArchitectureWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algosize-architecture.yml" },
  { name: "cloud spend", yaml: buildCostWorkflow({ origin: ORIGIN }),
    file: ".github/workflows/algosize-cost.yml" },
];

// ===========================================================================
group("every gate is safe to switch on");
// ===========================================================================
for (const g of GATES) {
  // The one universal rule: a missing secret is a notice and an exit 0.
  expect(/ALGOSIZE_API_KEY/.test(g.yaml),
    `${g.name} — reads the shared ALGOSIZE_API_KEY secret`);
  expect(/::notice::/.test(g.yaml),
    `${g.name} — has a notice path, so setup problems are not failures`);
  expect(!/\$\{\{\s*secrets\.\w+\s*\}\}/.test(g.yaml.replace(/ALGOSIZE_API_KEY/g, "")) ||
         (g.yaml.match(/secrets\./g) || []).every((_, i, a) => a.length <= 6),
    `${g.name} — needs no secret beyond that one`);
  expect(/permissions:/.test(g.yaml),
    `${g.name} — declares its permissions rather than inheriting the default token`);
  expect(!/permissions:[\s\S]{0,120}contents:\s*write/.test(g.yaml),
    `${g.name} — never asks for write access to the repository`);
}

// ===========================================================================
group("the estimator gate cannot reach a cloud account");
// ===========================================================================
{
  const yaml = buildEstimateWorkflow({ origin: ORIGIN });
  // The product promise is "no cloud-account connector, no credential
  // storage". A CI gate is the most natural place for that to erode, because
  // adding a role ARN would make the numbers better and the reviewer of that
  // pull request would probably say yes.
  const CLOUD_SECRETS = [
    "AWS_ACCESS_KEY", "AWS_SECRET", "AWS_SESSION_TOKEN", "AWS_ROLE",
    "role-to-assume", "aws-actions/configure-aws-credentials",
    "azure/login", "AZURE_CREDENTIALS", "google-github-actions/auth",
    "GOOGLE_APPLICATION_CREDENTIALS", "KUBECONFIG", "HCLOUD_TOKEN",
    "DIGITALOCEAN", "id-token: write",
  ];
  for (const s of CLOUD_SECRETS) {
    expect(!yaml.includes(s), `no ${s} anywhere in the estimator gate`);
  }
  expect(/not your bill/i.test(yaml),
    "and every comment it posts repeats that these are list prices, not an invoice");
  expect(/no cloud account was contacted/i.test(yaml),
    "…and says outright that nothing was contacted");
}

// ===========================================================================
group("a gate that fails says why, in the pull request");
// ===========================================================================
for (const g of GATES) {
  const fails = /exit 1/.test(g.yaml);
  if (!fails) { ok(`${g.name} — never fails a build by design`); continue; }
  expect(/::error::/.test(g.yaml),
    `${g.name} — an exit 1 is preceded by an ::error:: annotation`);
  expect(/gh pr comment|sticky|comment\.md|createComment/.test(g.yaml),
    `${g.name} — and the reasoning lands in the pull request, not only in the log`);
}

// ===========================================================================
group("thresholds default to annotate, not to fail");
// ===========================================================================
{
  // Switching a gate on must never be the thing that turns a repository red.
  // Whoever enables it should get a week of annotations first and raise the
  // threshold deliberately.
  expect(/monthlyCeilingUsd": null/.test(buildBudgetExample()),
    "the budget example ships with no ceiling — annotate first, gate later");
  expect(/arch_fail_on:"none"|arch_fail_on: *"none"/.test(buildArchitectureWorkflow({ origin: ORIGIN })),
    "the architecture gate defaults to arch_fail_on none");
  expect(/one bucket above/.test(buildOptimizerConfigExample()),
    "the optimizer example tells you to set a ceiling above the true complexity, " +
    "so timing noise cannot fail a build");
}

// ===========================================================================
group("the snippet endpoints serve the same YAML we commit");
// ===========================================================================
{
  const env = { SITE_ORIGIN: ORIGIN };
  const cases = [
    ["audit",        ciSnippetHandler,             buildWorkflow({ origin: ORIGIN })],
    ["optimizer",    ciOptimizerSnippetHandler,    buildOptimizerWorkflow({ origin: ORIGIN })],
    ["estimate",     ciEstimateSnippetHandler,     buildEstimateWorkflow({ origin: ORIGIN })],
    ["architecture", ciArchitectureSnippetHandler, buildArchitectureWorkflow({ origin: ORIGIN })],
  ];
  for (const [name, handler, expected] of cases) {
    const body = await handler(new Request("https://x/api/ci/" + name), env).json();
    expect(body.workflow === expected,
      `/api/ci/${name}-snippet serves the generated workflow verbatim`);
    expect(typeof body.filename === "string" && body.filename.startsWith(".github/workflows/"),
      `…and names where it goes`);
    // The snippet cannot contain a key: this endpoint has no access to key
    // plaintext (only sha256 hashes are stored), which makes that structural.
    expect(!/ask_live_/.test(body.workflow),
      `…and never embeds a key, only the secret's name`);
  }
}

// ===========================================================================
group("what we tell customers to run is what we run ourselves");
// ===========================================================================
for (const g of GATES) {
  const path = join(REPO, g.file);
  if (!existsSync(path)) {
    fail(`${g.name} — ${g.file} is committed in this repository`);
    continue;
  }
  ok(`${g.name} — ${g.file} is committed in this repository`);
  const onDisk = readFileSync(path, "utf8");
  // The audit workflow predates the generator and carries local edits; the
  // two generated ones must match byte for byte, or the advice we serve has
  // drifted from the thing we have actually watched run.
  if (g.file.includes("estimate") || g.file.includes("architecture")) {
    expect(onDisk === g.yaml,
      `…and is byte-identical to what /api/ci/*-snippet serves`);
  }
}

// ===========================================================================
group("the Worker's own pull-request gate actually covers the Worker");
// ===========================================================================
// Not a customer-facing gate — this is ours, and it is here because its
// failure mode is the quietest one in the file header: "a gate that silently
// stops running is worse than one that never ran." A workflow whose path
// filter does not match the change under review does not run, reports
// nothing, and leaves the pull request looking green.
//
// That happened. mcp.yml was the ONLY workflow running `npm test` on a pull
// request, and its filter listed MCP paths only — so a change to the router,
// the monitors, quota or auth matched nothing, ran no tests, and merged on
// the strength of four analyzer checks that scan the repo without executing
// it. It was caught by a PR rewriting the queue entrypoint, which is roughly
// the worst place to have no coverage.
{
  const wf = join(REPO, ".github", "workflows", "mcp.yml");
  expect(existsSync(wf), "the pull-request gate exists");
  const yaml = readFileSync(wf, "utf8");

  // The pull_request block specifically. The push block is deliberately
  // narrower — worker.yml already runs the suite on every push to main, and
  // duplicating it there would double every deploy's CI time for nothing.
  const prPaths = /pull_request:\s*\n\s*paths:\s*\n((?:\s*-\s*"[^"]+"\s*\n)+)/.exec(yaml);
  expect(Boolean(prPaths), "…and filters pull requests by path");
  const patterns = (prPaths ? prPaths[1] : "").match(/"([^"]+)"/g)?.map((x) => x.slice(1, -1)) || [];

  expect(patterns.includes("worker/**"),
    `the pull-request filter covers ALL of worker/ (got: ${patterns.join(", ")})`);

  // The specific regression: a filter that names sub-paths of worker/ instead
  // of worker/** is how this broke, and it reads as more precise rather than
  // less safe.
  const narrow = patterns.filter((x) => x.startsWith("worker/") && x !== "worker/**");
  expect(narrow.length === 0,
    `…and names no narrower worker/ path that would shadow it (found: ${narrow.join(", ") || "none"})`);

  expect(/run: npm test/.test(yaml),
    "…and the workflow does run the full suite, which is the only reason the filter matters");
}

// ===========================================================================
group("a spent allowance is a warning, never a red build");
// ===========================================================================
// The free tier is five runs a month and an active repository reaches that
// in an afternoon — this one did, the day its key was first set. Every gate
// then failed with a bare "returned HTTP 402", which reads to a reviewer as
// "this pull request is broken" rather than "the account is out of runs".
//
// The missing-key check has always been a notice-and-skip for exactly this
// reason, argued in its own comment: a workflow that goes red the moment it
// is pasted gets deleted, and a deleted gate costs the team its audit. Quota
// is the same failure with a worse shape, because a missing key is a
// one-time setup step and this recurs every month.
for (const g of GATES) {
  const metered = /api\/(ci\/runs|estimate|analyze\/)/.test(g.yaml);
  if (!metered) continue;

  // Two shapes in the wild: the curl gates test the status in bash, the
  // optimizer gate fetches from node and tests res.status. Both are checked,
  // because a guard that only understood bash reported the optimizer as
  // missing a branch it did not need — a false alarm that would have been
  // "fixed" by weakening the rule.
  const bashish = g.yaml.indexOf('HTTP" = "402"');
  const jsish   = g.yaml.indexOf("res.status === 402");
  const at = bashish >= 0 ? bashish : jsish;
  expect(at >= 0,
    `${g.name} — recognises 402 as its own case, not "some non-200"`);
  if (at < 0) continue;

  // The 402 branch must not fail the build. In bash that means exit 0 rather
  // than falling into the generic non-200 path; in JS it means `continue`.
  const branch = g.yaml.slice(at);
  const end = bashish >= 0 ? branch.indexOf("\n          fi") : branch.indexOf("\n              }");
  const body = branch.slice(0, end > 0 ? end : 400);
  expect((/exit 0/.test(body) || /continue;/.test(body)) && !/exit 1/.test(body),
    `${g.name} — the 402 branch cannot fail a build over a billing state`);
  expect(/::warning::/.test(body) && !/::error::/.test(body),
    `${g.name} — and annotates it as a warning rather than an error`);
  expect(/\.message/.test(body),
    `${g.name} — relaying the server's own sentence, not a bare status code`);
}

// The audit gate carries one extra obligation: silence is not an acceptable
// way to report that no audit ran. A reviewer scanning the thread must not
// read a missing comment as a clean bill of health.
{
  const audit = GATES.find((g) => g.name === "dependency audit");
  expect(/audit\.outputs\.quota == 'true'/.test(audit.yaml),
    "the audit gate comments when the allowance is spent");
  expect(/not run/i.test(audit.yaml) && /not a clean result/i.test(audit.yaml),
    "…saying plainly that the dependencies were NOT checked");
}

// ===========================================================================
group("every generated gate is valid bash, and its jq actually interpolates");
// ===========================================================================
// These generators are JS template literals, so a single backslash never
// reaches the YAML: `\\` + newline is a JS line continuation that deletes the
// newline, and `\\(` collapses to `(`. Both mistakes shipped — the estimate and
// architecture gates had their multi-line shell crushed onto one line, an
// unescaped `\\(` that made `find` a bash syntax error, and jq interpolations
// written `"x=(.y)"` instead of `"x=\\(.y)"`, which emits the literal text
// rather than the value.
//
// It stayed invisible for weeks because ALGOSIZE_API_KEY was never set on this
// repository: every run skipped at the key check and reported success. The
// moment a real key landed, two of the three gates failed on their first run.
// A green CI check that never executed its own body proves nothing, so these
// assertions read the generated YAML rather than trusting that it ran.
{
  const { execFileSync } = await import("node:child_process");
  const { writeFileSync, mkdtempSync } = await import("node:fs");
  const { tmpdir } = await import("node:os");
  const { join } = await import("node:path");
  const dir = mkdtempSync(join(tmpdir(), "gates-"));

  for (const g of GATES) {
    // Every `run: |` block, dedented, with GitHub expressions blanked — they
    // are substituted before bash ever sees them, and `${{ ... }}` is not
    // valid shell on its own.
    const blocks = [...g.yaml.matchAll(/run: \|\n([\s\S]*?)(?=\n {6}- name:|\n {6}- uses:|\n *$)/g)]
      .map((m) => m[1].replace(/\$\{\{[^}]*\}\}/g, "X"))
      .map((b) => b.split("\n").map((l) => l.replace(/^ {10}/, "")).join("\n"));

    let bad = null;
    blocks.forEach((b, i) => {
      // A heredoc body is another language (python here); bash -n still parses
      // the heredoc itself, which is what we want to check.
      const f = join(dir, `${g.name.replace(/\W/g, "_")}-${i}.sh`);
      writeFileSync(f, b);
      try { execFileSync("bash", ["-n", f], { stdio: "pipe" }); }
      catch (err) { if (!bad) bad = String(err.stderr || err).split("\n")[0]; }
    });
    expect(bad === null, `${g.name} — every run block parses as bash (${bad || "ok"})`);

    // The collapse signature: a `find`/`curl`/`jq` line carrying a long run of
    // spaces is a line continuation that JS ate.
    //
    // It cannot tell that from deliberate column alignment, and it should not
    // be loosened to try: this assertion caught two gates that had never once
    // run, and a heuristic that occasionally asks an author to use fewer
    // alignment spaces is cheap next to one that misses a dead workflow. If
    // it fires on a line you wrote on purpose, shorten the padding.
    const collapsed = g.yaml.split("\n").find((l) => /\s{8,}\S/.test(l.trim()));
    expect(!collapsed,
      `${g.name} — no line-continuation was swallowed into one long line`);

    // jq interpolation must keep its backslash, or it prints its own source.
    const badJq = g.yaml.split("\n").find((l) =>
      /^\s*[|"']*\s*"?\w+=\((\.|\$)/.test(l) && !l.includes("=\\("));
    expect(!badJq,
      `${g.name} — jq interpolations are \\( … ), not bare ( … ) (${badJq ? badJq.trim() : "ok"})`);
  }
}

console.log("");
if (failures) {
  console.log(`\x1b[31m  ${failures} ci-gate test(s) failed\x1b[0m`);
  process.exit(1);
}
console.log("\x1b[32m  all ci-gate tests passed\x1b[0m");
