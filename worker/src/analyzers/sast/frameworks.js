/**
 * Score to confidence, with a hard cap that the score alone cannot express.
 *
 * `strong` is true when at least one signal was something other than a
 * directory name. Without that cap, two weight-1 directories sum to 2 and
 * report "medium" — which is how a static site with `pages/` and `app/` gets
 * announced as Next.js. Accumulating weak evidence does not make it strong:
 * a hundred directory matches still do not show that anybody installed the
 * framework, so directory-only detections are pinned at low however many fire.
 */
const CONFIDENCE_FOR = (score, strong) => {
  if (!strong) return "low";
  return score >= 3 ? "high" : score >= 2 ? "medium" : "low";
};

/**
 * Detect frameworks from a repository's shape.
 *
 * Pure: every input is supplied by the caller, so this is testable without a
 * repository, a network, or a filesystem.
 *
 *   paths        every non-ignored path in the repository
 *   dependencies package/module names gathered from manifests, lowercased
 *   extensions   Set of extensions present, for the React/.jsx signal
 *   imports      import strings sampled from source, for stdlib frameworks
 */
export function detectFrameworks({ paths = [], dependencies = [], extensions = new Set(), imports = [] } = {}) {
  const lowerPaths = paths.map((p) => String(p).toLowerCase());
  const pathSet = new Set(lowerPaths);
  const deps = new Set(dependencies.map((d) => String(d).toLowerCase()));
  const importSet = new Set(imports.map((i) => String(i).toLowerCase()));

  const out = [];
  for (const fw of FRAMEWORKS) {
    let score = 0;
    // Whether any signal other than a directory name fired. See CONFIDENCE_FOR.
    let strong = false;
    const evidence = [];

    for (const dep of fw.dependency || []) {
      if (deps.has(dep.toLowerCase())) {
        score += WEIGHT.dependency;
        strong = true;
        evidence.push(`dependency: ${dep}`);
      }
    }
    for (const file of fw.configFile || []) {
      const hit = matchPath(lowerPaths, pathSet, file);
      if (hit) { score += WEIGHT.configFile; strong = true; evidence.push(hit); }
    }
    for (const file of fw.markerFile || []) {
      const hit = matchPath(lowerPaths, pathSet, file);
      if (hit) { score += WEIGHT.markerFile; strong = true; evidence.push(hit); }
    }
    for (const dir of fw.directory || []) {
      const d = dir.toLowerCase();
      const hit = lowerPaths.some((p) => p === d || p.startsWith(d + "/") || p.includes("/" + d + "/"));
      if (hit) { score += WEIGHT.directory; evidence.push(`directory: ${dir}/`); }
    }
    for (const imp of fw.importPattern || []) {
      if (importSet.has(imp.toLowerCase())) {
        score += WEIGHT.dependency;
        strong = true;
        evidence.push(`import: ${imp}`);
      }
    }

    // React earns a second signal from .jsx/.tsx, but only alongside the
    // dependency — a .jsx file with no react dependency is Preact, Solid, or
    // somebody's build artifact, and claiming React from the extension alone
    // is the classic false positive this weighting exists to prevent.
    if (fw.id === "react" && score > 0 && (extensions.has("jsx") || extensions.has("tsx"))) {
      score += WEIGHT.markerFile;
      evidence.push("jsx/tsx files present");
    }

    if (score > 0) {
      out.push({
        name: fw.name,
        language: fw.language,
        confidence: CONFIDENCE_FOR(score, strong),
        score,
        evidence,
      });
    }
  }

  // Strongest first, then alphabetical so the list is stable across scans of
  // an unchanged repository — a report that reshuffles between runs looks like
  // it found something new.
  out.sort((a, b) => b.score - a.score || a.name.localeCompare(b.name));
  return out;
}

/**
 * Match a signature file against the tree.
 *
 * A signature containing a slash is anchored to a path suffix (`config/routes.rb`
 * must be that path, not any file named routes.rb); a bare name matches any
 * basename at any depth. Returns the evidence string, or null.
 */
function matchPath(lowerPaths, pathSet, signature) {
  const sig = signature.toLowerCase();
  if (sig.includes("/")) {
    const hit = pathSet.has(sig) || lowerPaths.find((p) => p.endsWith("/" + sig));
    return hit ? `config: ${signature}` : null;
  }
  const hit = lowerPaths.find((p) => p === sig || p.endsWith("/" + sig));
  return hit ? `file: ${signature}` : null;
}
