// Framework signatures — declarative, and every detection carries its reason.
//
// ---------------------------------------------------------------------------
// WHY EVERY SIGNAL IS WEIGHTED RATHER THAN BOOLEAN
// ---------------------------------------------------------------------------
//
// Framework detection is guessing, and the useful question is not "did we
// guess?" but "how much would you bet on this guess, and on what basis?"
//
// A dependency entry is close to proof: `"next": "^14"` in package.json means
// somebody installed Next.js. A directory name is not: `app/` means Next's app
// router, or Rails, or nothing at all. A repository with a `pages/` folder and
// no `next` dependency is a static site, and reporting "Next.js detected"
// there sends a reviewer looking for `getServerSideProps` in a project that
// has never had any.
//
// So each signal carries a weight, detection sums them, and the result exposes
// both the confidence and the evidence list that produced it. A reader who
// disagrees with a detection can see exactly which signal caused it — which is
// the difference between a heuristic you can correct and one you must trust.
//
// Thresholds: >= 3 high, >= 2 medium, 1 low — and one cap on top, because the
// sum alone gets this wrong. A detection built ONLY from directory names never
// rises above low, however many match: accumulating weak evidence does not
// make it strong, and two conventional folder names summing to "medium" is
// precisely how a static site gets announced as Next.js.
//
// A lone weak signal is still reported rather than suppressed, because "we saw
// a Rails-shaped layout and no Gemfile" is worth showing to someone deciding
// whether the scan looked in the right places.

/**
 * Signal kinds and what they are worth.
 *
 *   dependency  a name in a manifest's dependency map          3  (near-proof)
 *   configFile  a framework's own config file at any depth     3  (near-proof)
 *   markerFile  a file the framework's tooling generates       2
 *   directory   a conventional directory layout                1  (weak alone)
 */
